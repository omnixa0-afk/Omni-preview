namespace Omni.Windows.App.Features.Calls;

/// <summary>
/// Кто из пришедших кадров доедет до кодировщика.
///
/// Источников два, и они разной природы — поэтому и правил два.
///
/// КАМЕРА объявляет свою частоту и держит её ровно: 30 кадров в секунду значит 30, с шагом
/// 33 мс. Такой источник прореживается СЧЁТОМ: берём wanted из каждых source. Дедлайн здесь
/// работает плохо и это измерено — см. <see cref="SelectFromDeclaredRate"/>.
///
/// ЭКРАН частоты не объявляет вовсе: Windows.Graphics.Capture отдаёт кадр, когда на экране
/// что-то изменилось. Считать не от чего, и до 2026-08-27 прореживания не было вообще:
/// <c>ActiveCaptureSourceFps</c> подставлял согласованные 30, правило «хотим не меньше, чем даёт
/// источник» срабатывало на равенстве, и в кодировщик уходило ВСЁ. Живой замер того дня: профиль
/// 30 к/с, а `sentFps` на демонстрации экрана 33-38 — четверть кадров лишняя, и каждый стоит
/// перевода цвета, копии и перехода через FFI.
///
/// Для такого источника правило — ДЕДЛАЙН: кадр берём, если с прошлого взятого прошло не меньше
/// целевого интервала.
/// </summary>
internal static class CallVideoFrameSelector
{
    /// <summary>
    /// Допуск дедлайна. Нужен ровно для одного случая: источник событий, который сам идёт
    /// примерно с целевой частотой (статичный экран обновляется 30 раз в секунду при цели 30).
    /// Без допуска дрожание в пару миллисекунд роняло бы каждый второй кадр и давало 15 к/с
    /// вместо 30 — та самая ловушка квантования, из-за которой камеру прореживают счётом.
    ///
    /// Цена допуска — верхняя граница перебора: источник, идущий быстрее 1000/(интервал-допуск),
    /// пройдёт целиком. При цели 30 это 35 к/с, и это заметно лучше 60, которые шли раньше.
    /// </summary>
    internal const int DeadlineToleranceMs = 5;

    /// <summary>
    /// Источник с ОБЪЯВЛЕННОЙ частотой (камера): берём wanted кадров из каждых source, размазывая
    /// выбор настолько ровно, насколько позволяет источник (24 из 30 → четыре кадра из пяти).
    ///
    /// Дедлайн здесь неверен и это измерено: у источника с фиксированным шагом он квантует
    /// результат вниз до делителя частоты источника. При камере 30 к/с и цели 24 (интервал 41 мс)
    /// каждый второй кадр приходит на 33-й миллисекунде — слишком рано, — выбрасывается, и
    /// получается 15 к/с вместо 24, да ещё с рывками 33/66 мс. См. docs/bugs/media-hitching.md.
    /// </summary>
    /// <param name="credit">Накопитель выбора; принадлежит вызывающему и переживает вызовы.</param>
    internal static bool SelectFromDeclaredRate(int wantedFps, int sourceFps, ref long credit)
    {
        if (sourceFps <= 0 || wantedFps >= sourceFps)
        {
            return true;
        }

        credit += wantedFps;
        if (credit < sourceFps)
        {
            return false;
        }

        credit -= sourceFps;
        return true;
    }

    /// <summary>
    /// Источник БЕЗ объявленной частоты (демонстрация экрана): берём кадр, если с прошлого взятого
    /// прошёл целевой интервал за вычетом допуска.
    /// </summary>
    /// <param name="lastSelectedAtMs">
    /// Когда был взят прошлый кадр; 0 = ещё ни одного. Принадлежит вызывающему.
    /// </param>
    internal static bool SelectFromEventDrivenSource(int wantedFps, long nowMs, ref long lastSelectedAtMs)
    {
        if (wantedFps <= 0)
        {
            return true;
        }

        long intervalMs = System.Math.Max(1, 1000 / wantedFps);
        long minimumGapMs = System.Math.Max(1, intervalMs - DeadlineToleranceMs);
        if (lastSelectedAtMs != 0 && nowMs - lastSelectedAtMs < minimumGapMs)
        {
            return false;
        }

        lastSelectedAtMs = nowMs;
        return true;
    }
}
